/** Deterministically select one of the 100 motivational warfare lines for any given date or ID */
export function getWarfareLine(dateStr: string): string {
  if (!dateStr) return WARFARE_LINES[0];
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const idx = Math.abs(hash) % WARFARE_LINES.length;
  return WARFARE_LINES[idx];
}
